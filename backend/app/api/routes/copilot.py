from fastapi import APIRouter, HTTPException, Depends
from sqlalchemy.ext.asyncio import AsyncSession
from app.db.session import get_db
from app.schemas.contracts import (
    CopilotChatRequest,
    CopilotChatResponse,
    CopilotStructuredResponseSchema,
    EvidenceReferenceSchema
)
from app.core.redaction import redact_text
from app.models.entities import CopilotInteractionModel
import datetime
import uuid

router = APIRouter(prefix="/copilot", tags=["Copilot"])


@router.post("/chat", response_model=CopilotChatResponse)
async def copilot_chat(
    req: CopilotChatRequest,
    db: AsyncSession = Depends(get_db)
):
    """
    AI Investigation Copilot endpoint.
    Processes user inquiries grounded strictly in redacted finding context.
    Returns 5 structured analytical sections without inventing facts.
    """
    ctx = req.findingContext
    last_user_message = req.messages[-1].content if req.messages else "Explain this finding."
    
    # Task 2: Redact user prompt before persistence and analysis to prevent PII leakage
    redacted_user_prompt = redact_text(last_user_message)

    # Determine topic of interest
    finding_title = ctx.title
    endpoint = redact_text(ctx.endpoint)
    affected_url = redact_text(ctx.affectedUrl)
    dpdp_section = ctx.dpdpSection

    # Sanitize observed evidence context
    raw_payload = str(ctx.observedEvidence.get('sanitizedPayload', 'Forensic packet trace recorded in sandbox environment.'))
    sanitized_payload = redact_text(raw_payload)

    # Build grounded analytical sections with sanitized inputs
    what_we_observed = [
        f"Target endpoint: '{endpoint}' on {affected_url}.",
        f"Statutory mandate: {dpdp_section}.",
        f"Observed behavioral signature: {sanitized_payload}"
    ]

    why_it_matters = (
        f"Under DPDP Act 2023 {dpdp_section}, Data Fiduciaries must ensure personal data protection. "
        f"Failure to secure this endpoint exposes principals to identity misuse and the entity to potential regulatory enforcement exposure under statutory schedules."
    )

    what_remains_uncertain = (
        "Sandbox observations confirm technical behavior on visited routes. "
        "Whether supplementary backend firewalls or unobserved VPC policies restrict external traffic cannot be confirmed solely from client-side network traces."
    )

    recommended_actions = [redact_text(s) for s in (ctx.remediationSteps or [
        "Enforce strict object-level authorization checks prior to record delivery.",
        "Implement data masking and audit logging under DPDP §8(5)."
    ])]

    how_to_verify = [
        "Deploy the proposed code patch in the isolated staging testbed.",
        "Run the verification probe in the Fix & Verify workspace to confirm HTTP 403 Forbidden on cross-tenant requests."
    ]

    evidence_refs = [
        EvidenceReferenceSchema(
            id=f"EV-{ctx.findingId[:8]}",
            label="Observed HTTP Packet Trace",
            snippet=sanitized_payload,
            sourceType="network_packet"
        )
    ]

    summary = f"Analysis of {ctx.findingId} ({finding_title}): Grounded technical evidence identifies potential risk under {dpdp_section}."

    structured = CopilotStructuredResponseSchema(
        summary=summary,
        whatWeObserved=what_we_observed,
        whyItMatters=why_it_matters,
        whatRemainsUncertain=what_remains_uncertain,
        recommendedActions=recommended_actions,
        howToVerify=how_to_verify,
        evidenceReferences=evidence_refs,
        disclaimer="Analysis generated by DPDP-Guard Copilot demo provider grounded in technical finding metadata. This is technical security analysis, not formal legal counsel."
    )

    # Persist interaction with sanitized prompt
    interaction = CopilotInteractionModel(
        id=f"COPILOT-{uuid.uuid4().hex[:8].upper()}",
        finding_id=ctx.findingId,
        user_prompt=redacted_user_prompt,
        provider_used="demo",
        structured_response=structured.model_dump(),
        created_at=datetime.datetime.now(datetime.timezone.utc)
    )
    db.add(interaction)
    await db.commit()

    return CopilotChatResponse(
        summary=summary,
        structuredResponse=structured,
        isDemoResponse=True,
        suggestedNextQuestions=[
            "What could happen if this issue is not fixed?",
            "How should a developer fix it?",
            "How can I verify the fix in the sandbox?"
        ]
    )
